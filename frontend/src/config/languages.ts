type DisplayNamesConstructor = new (
  locales: string[],
  options: { type: 'language' },
) => { of(code: string): string | undefined };

function languageDisplayName(code: string) {
  const displayNamesConstructor = (Intl as unknown as { DisplayNames?: DisplayNamesConstructor }).DisplayNames;
  const displayName = displayNamesConstructor
    ? new displayNamesConstructor(['en'], { type: 'language' }).of(code)
    : undefined;

  return displayName ? `${displayName} (${code})` : code.toUpperCase();
}

function buildLanguageOptions(): LanguageOption[] {
  const uniqueCodes = Array.from(
    new Set([
      ...PRIORITY_LANGUAGE_CODES,
      ...ISO_639_1_LANGUAGE_CODES,
      ...EXTRA_LANGUAGE_CODES,
    ]),
  );
  const priorityCodes = new Set<string>(PRIORITY_LANGUAGE_CODES);
  const priorityOptions = PRIORITY_LANGUAGE_CODES.map((code) => [code, languageDisplayName(code)] as const);
  const remainingOptions = uniqueCodes
    .filter((code) => !priorityCodes.has(code))
    .map((code) => [code, languageDisplayName(code)] as const)
    .sort((a, b) => a[1].localeCompare(b[1]));

  return [...priorityOptions, ...remainingOptions];
}

export const LANGUAGE_OPTIONS = buildLanguageOptions();

const LANGUAGE_LABELS = new Map(LANGUAGE_OPTIONS);

export function getLanguageLabel(code: string) {
  return LANGUAGE_LABELS.get(code) ?? code.toUpperCase();
}
